"""Add a small fleet of SYNTHETIC battery packs to the demo CSV bundle (engines/database/csv_bundle/).

Every row written here is labelled SYNTHETIC. The packs are made-up and cover the decision range:
healthy and worn NMC, two LFP packs, an end-of-life pack and a pack with a critical thermal event.
Telemetry is generated by coulomb counting at the pack's measured capacity, so the data-quality checks
(charge balance, regen sign, estimate agreement) can pass. Current: discharge negative, charge positive.

Run: python engines/database/make_demo_fleet.py   (re-runnable: DEMO-EV-PACK-001 rows are kept as they are,
the fleet rows are regenerated from the seeds below). Then: just db
"""
from __future__ import annotations

import csv
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

CSV_DIR = Path(__file__).resolve().parent / "csv_bundle"
BASE_ID = "DEMO-EV-PACK-001"
STEP_MIN = 5

# chemistry -> (label in battery_asset, cell OCV at 0% and 100% SOC, min/max cell V, nominal cell V, cathode label)
CHEM = {
    "NMC": ("NMC (nickel manganese cobalt)", (3.35, 4.15), (3.0, 4.2), 3.7, "NMC oxide"),
    "LFP": ("LFP (lithium iron phosphate)", (3.15, 3.35), (2.5, 3.65), 3.2, "LFP (lithium iron phosphate)"),
    "NCA": ("NCA", (3.30, 4.10), (3.0, 4.2), 3.6, "NCA oxide"),
}

# id, vehicle, chemistry, series, parallel, rated Ah, measured Ah (newest test), cycles, resistance mOhm, ambient C, thermal event
FLEET = [
    ("DEMO-EV-PACK-002", "DEMO-EV-002", "NMC", 96, 36, 180, 171.9, 480, 2.1, 22.0, False),
    ("DEMO-EV-PACK-003", "DEMO-EV-003", "NMC", 96, 40, 200, 158.0, 1450, 3.4, 23.0, False),
    ("DEMO-LFP-PACK-004", "DEMO-BUS-004", "LFP", 100, 50, 120, 101.0, 1900, 4.1, 24.0, False),
    ("DEMO-LFP-PACK-005", "DEMO-VAN-005", "LFP", 96, 60, 160, 114.0, 2600, 5.0, 24.0, False),
    ("DEMO-EV-PACK-006", "DEMO-EV-006", "NMC", 96, 40, 200, 124.0, 2100, 6.2, 25.0, False),
    ("DEMO-EV-PACK-007", "DEMO-EV-007", "NCA", 96, 40, 200, 176.0, 900, 2.8, 26.0, True),
]
TEST_DATES = ["2024-06-30", "2024-12-31", "2025-06-30", "2025-12-31", "2026-06-30"]


def read(name: str) -> tuple[list[str], list[list[str]]]:
    with open(CSV_DIR / f"{name}.csv", encoding="utf-8", newline="") as fh:
        rows = list(csv.reader(fh))
    return rows[0], rows[1:]


def write(name: str, header: list[str], rows: list[list]) -> None:
    with open(CSV_DIR / f"{name}.csv", "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


def keep_base(header: list[str], rows: list[list[str]], col: str = "asset_id") -> list[list[str]]:
    i = header.index(col)
    return [r for r in rows if r[i] == BASE_ID]


def asset_rows(pid, vehicle, chem, ns, np_, rated, cycles):
    label, _, (vmin, vmax), vnom, _ = CHEM[chem]
    nominal_v = round(ns * vnom, 1)
    return [
        ("asset_id", pid), ("vehicle_id", vehicle), ("battery_type", "Lithium-ion traction battery"),
        ("chemistry", label), ("cell_format", "21700 cylindrical (illustrative)"),
        ("series_parallel_configuration", f"{ns}s{np_}p"), ("cell_count", ns * np_),
        ("nominal_voltage_V", nominal_v), ("max_voltage_V", round(ns * vmax, 1)), ("min_voltage_V", round(ns * vmin, 1)),
        ("nominal_capacity_Ah", rated), ("nominal_energy_kWh", round(nominal_v * rated / 1000, 2)),
        ("pack_mass_kg", round(450 * rated / 200)), ("manufacture_date", "2024-01-15"),
        ("commissioning_date", "2024-02-01"), ("warranty_end_date", "2032-02-01"),
        ("demo_status", "SYNTHETIC DEMO — not a real vehicle or manufacturer specification"),
    ]


def health_rows(pid, rated, measured, cycles, r_final):
    n = len(TEST_DATES)
    out = []
    for k, date in enumerate(TEST_DATES):
        frac = (k + 1) / n
        # capacity fades a little faster early on: square-root shaped, ending exactly at the newest test
        cap = rated - (rated - measured) * (frac ** 0.8)
        r = 1.8 + (r_final - 1.8) * frac
        cyc = round(cycles * frac)
        soh = round(cap / rated * 100, 1)
        rul = max(0, round((soh - 60) / max(1e-9, (100 - soh)) * cyc * 0.9)) if soh < 100 else 2000
        out.append([date, pid, cyc, round(cap, 1), rated, soh, round(r, 2), rul, "Illustrative capacity check", "SYNTHETIC"])
    return out


def telemetry_rows(pid, chem, ns, rated, measured, soh, r_mohm, ambient, thermal, rng):
    _, (o0, o1), _, _, _ = CHEM[chem]
    t = datetime(2026, 10, 20, 8, 0, tzinfo=timezone.utc)
    soc = 94.0
    rows = []
    drive_steps, charge_steps = 60, 24
    for k in range(drive_steps + charge_steps):
        if k < drive_steps:
            if k % 11 == 7:                                   # short regenerative pulse: current flips positive
                amps, state = rng.uniform(0.03, 0.08) * rated, "REGENERATIVE_BRAKING"
            else:
                amps, state = -rng.uniform(0.04, 0.16) * rated, "DRIVING"
        else:
            amps, state = 0.2 * rated, "CHARGING"
        amps = round(amps, 1)
        # coulomb counting at the measured capacity: the SOC the current explains
        soc = min(100.0, max(2.0, soc + amps * (STEP_MIN / 60) / measured * 100))
        ocv = ns * (o0 + (o1 - o0) * soc / 100)
        volts = round(ocv + amps * (r_mohm / 1000) + rng.gauss(0, 0.12), 2)    # IR drop plus ADC noise
        hot = ambient + 3 + abs(amps) / rated * 40 + k * 0.03 + rng.uniform(-0.4, 0.4)   # slow warm-up plus sensor noise
        if thermal and k >= 40:
            hot += (k - 39) * 0.75                            # runaway-like climb: the safety gate must see it
        tmax = round(hot, 1)
        rows.append([t.strftime("%Y-%m-%dT%H:%M:%SZ"), pid, round(soc, 1), soh, volts, amps, tmax, round(tmax - 2.2, 1),
                     round(ambient + k * 0.02, 1), round(volts * amps / 1000, 4), state, "SYNTHETIC"])
        t += timedelta(minutes=STEP_MIN)
    return rows


def main() -> None:
    rng_seed = 20261020
    h, rows = read("battery_asset")
    # battery_asset is (field, value) for one pack; a leading asset_id column lets one table hold the whole fleet.
    base_pairs = rows if h == ["field", "value"] else [[r[1], r[2]] for r in rows if r[0] == BASE_ID]
    asset_out = [[BASE_ID, f, v] for f, v in base_pairs]

    tel_h, tel = read("telemetry"); tel_out = keep_base(tel_h, tel)
    hh_h, hh = read("health_history"); hh_out = keep_base(hh_h, hh)
    ev_h, ev = read("safety_events"); ev_out = keep_base(ev_h, ev)
    ch_h, ch = read("charge_sessions"); ch_out = keep_base(ch_h, ch)
    md_h, md = read("modules"); md_out = keep_base(md_h, md)
    mt_h, mt = read("materials_recycling"); mt_base = keep_base(mt_h, mt, "asset_id"); mt_out = list(mt_base)

    evt_n = len(ev_out)
    for idx, (pid, veh, chem, ns, np_, rated, measured, cycles, r_final, amb, thermal) in enumerate(FLEET):
        rng = random.Random(rng_seed + idx)
        soh = round(measured / rated * 100, 1)
        asset_out += [[pid, f, v] for f, v in asset_rows(pid, veh, chem, ns, np_, rated, cycles)]
        hh_out += health_rows(pid, rated, measured, cycles, r_final)
        tel_out += telemetry_rows(pid, chem, ns, rated, measured, soh, r_final, amb, thermal, rng)
        label, _, _, vnom, cathode = CHEM[chem]
        for m in range(1, 5):
            md_out.append([f"MOD-{m:02d}", pid, ns // 4, np_, (ns // 4) * np_, round(ns / 4 * vnom, 1), rated, chem,
                           "Illustrative module grouping"])
        scale = rated / 200
        for r in mt_base:
            mass = round(float(r[3]) * scale)
            material = cathode if r[1] == "Cathode active material" else r[2]
            mt_out.append([pid, r[1], material, mass, r[4], r[5], r[6], r[7]])
        # one routine charge session each, plus events
        ch_out.append([f"CHG-{pid[-3:]}", pid, "2026-10-19T18:00:00Z", "2026-10-19T19:00:00Z", "AC_LEVEL_2", 30, 90,
                       round(ns * vnom * rated / 1000 * 0.6, 1), 11, round(amb + 4, 1), "COMPLETED", "SYNTHETIC"])
        evt_n += 1
        if thermal:
            ev_out.append([f"EVT-{evt_n:03d}", pid, "2026-10-20T12:15:00Z", "CELL_OVER_TEMPERATURE", "CRITICAL",
                           "64 C", "60.0 C critical threshold", "OPEN",
                           "Pack isolated; do not return to service before inspection", "SYNTHETIC"])
        elif soh < 80:
            ev_out.append([f"EVT-{evt_n:03d}", pid, "2026-09-12T09:10:00Z", "CELL_VOLTAGE_IMBALANCE", "MEDIUM",
                           "52 mV spread", "50 mV service threshold", "MONITORING",
                           "Flagged for next scheduled inspection", "SYNTHETIC"])
        else:
            ev_out.append([f"EVT-{evt_n:03d}", pid, "2026-10-02T17:40:00Z", "INSULATION_RESISTANCE_CHECK", "INFO",
                           "1.9 MOhm", "1.0 MOhm minimum example threshold", "CLOSED", "Routine check passed", "SYNTHETIC"])

    write("battery_asset", ["asset_id", "field", "value"], asset_out)
    write("telemetry", tel_h, tel_out)
    write("health_history", hh_h, hh_out)
    write("safety_events", ev_h, ev_out)
    write("charge_sessions", ch_h, ch_out)
    write("modules", md_h, md_out)
    write("materials_recycling", mt_h, mt_out)
    print(f"battery packs: {1 + len(FLEET)}  (telemetry rows: {len(tel_out)})")


if __name__ == "__main__":
    main()
